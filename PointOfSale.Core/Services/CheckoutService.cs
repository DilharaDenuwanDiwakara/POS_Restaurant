using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading.Tasks;
using PointOfSale.Core.DTOs;
using PointOfSale.Core.Interfaces.Repositories.Sales;
using PointOfSale.Core.Models.Sales;

namespace PointOfSale.Core.Services
{
    public sealed class BankPromotionApplication
    {
        public BankPromoWithExclusionsDto Promotion { get; set; }
        public decimal EligibleSubtotal { get; set; }
        public decimal DiscountAmount { get; set; }
        public string PromoType => DiscountAmount > 0 ? "BANK" : null;
        public int? PromoBankId => DiscountAmount > 0 ? (int?)Promotion.BankId : null;
    }

    public sealed class CheckoutService
    {
        private readonly ISalesRepository _sales;
        public CheckoutService(ISalesRepository sales)
        {
            _sales = sales ?? throw new ArgumentNullException(nameof(sales));
        }

        // SalesLine is this application's cart item. Never alter its existing discounts.
        public async Task<BankPromotionApplication> ApplyBankPromotionAsync(string bin, List<SalesLine> cart)
        {
            if (bin == null || (bin.Length < 6 || bin.Length > 8) || bin.Any(c => c < '0' || c > '9'))
                throw new ArgumentException("Enter 6 to 8 digits for the card BIN.", nameof(bin));
            if (cart == null) throw new ArgumentNullException(nameof(cart));
            var promotion = await _sales.GetBankPromoWithExclusionsAsync(bin);
            return CalculateBankPromotion(promotion, cart);
        }

        public static BankPromotionApplication CalculateBankPromotion(BankPromoWithExclusionsDto promotion, IEnumerable<SalesLine> cart)
        {
            var result = new BankPromotionApplication { Promotion = promotion };
            if (promotion == null) return result;
            if (promotion.BankId <= 0 || promotion.BankPromotionId <= 0 ||
                promotion.DiscountPercentage <= 0 || promotion.DiscountPercentage > 100)
                throw new InvalidOperationException("The bank promotion configuration is invalid.");
            if (promotion.MinBillAmount < 0 || promotion.MaxBillAmount < 0 ||
                promotion.MinBillAmount > promotion.MaxBillAmount)
                throw new InvalidOperationException("The bank promotion bill limits are invalid.");
            var lines = cart.ToList();
            // Bill thresholds include every line after line discounts, before the bank discount.
            var billTotal = Math.Round(lines.Sum(line => line.Amount), 2, MidpointRounding.AwayFromZero);
            if (billTotal < promotion.MinBillAmount || billTotal > promotion.MaxBillAmount)
                return result;
            var exclusions = new HashSet<int>(promotion.ExcludedVariantIds);
            result.EligibleSubtotal = lines.Where(line => line.LineDiscount == 0 &&
                !line.IsAutoGeneratedPromotionLine && !exclusions.Contains(line.ProductId) &&
                line.Quantity > 0 && line.UnitPrice > 0).Sum(line => line.Quantity * line.UnitPrice);
            result.DiscountAmount = Math.Round(result.EligibleSubtotal * promotion.DiscountPercentage / 100m,
                2, MidpointRounding.AwayFromZero);
            return result;
        }
    }
}
